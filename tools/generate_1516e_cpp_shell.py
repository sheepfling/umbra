"""Generate the bounded IEEE 1516e-2010 C++ ambassador shell.

The official header is the source of truth. Every pure virtual
``RTIambassador`` service is copied into a concrete private class. A small
provider-owned reference slice covers federation membership, declaration
lookup/publication, object registration/update callbacks, and interaction
publish/subscribe/send callbacks; all remaining services continue to throw
``RTIinternalError`` until their own gate exists.
"""

