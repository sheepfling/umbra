def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, default=DEFAULT_HEADER)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = _render(_declarations(args.header.resolve()))
        output = args.output.resolve()
        if args.check:
            if output.read_text(encoding="utf-8") != expected:
                print("IEEE 1516e C++ shell drifted", file=sys.stderr)
                return 1
            print("IEEE 1516e C++ bounded shell: PASS (151 service overrides)")
            return 0
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding="utf-8")
        print(f"wrote IEEE 1516e C++ reference shell to {output}")
        return 0
    except (OSError, ValueError) as error:
        print(f"IEEE 1516e C++ bounded shell: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
